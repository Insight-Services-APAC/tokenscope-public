#!/usr/bin/env node
/*
 * check-handler-rls-context.mjs — CI guard for docs/design/rls-enforcement.md.
 *
 * THE RULE: every connection to Postgres carries an RLS identity, and which
 * identity it carries is decided by the LANE it belongs to — not by the code
 * that happens to run on it. A handler under server/api/** that calls
 * server/db/index.ts::getDb() directly is on no lane at all: its queries run
 * with NO RLS context, so under `FORCE ROW LEVEL SECURITY` its SELECTs return
 * zero rows silently and its writes error.
 *
 * The three lanes and their helpers:
 *   - request → server/db/request-rls.ts::withRequestRls(event, fn)
 *   - machine → server/db/machine-rls.ts::withMachineRls(bearer, fn)
 *               (or withDeferredMachineRls when the identity is discovered
 *               inside the transaction — see setup/redeem.post.ts)
 *   - worker  → a dedicated pool carrying a connection-level GUC
 *   - tests / pre-Epic-4 callers → server/db/rls.ts::withRlsContext directly
 *
 * This check fails CI when a file under server/api/** calls getDb() and is not
 * in ALLOWLIST below. Shrinking the allowlist never fails the check; growing it
 * requires editing this file, which is the point — a new entry has to be argued
 * for in a diff, next to its reason.
 *
 * EVERY ENTRY CARRIES A REASON. An allowlist without reasons is how this debt
 * came back: the previous revision listed 47 paths generated by
 * `grep -rl 'getDb(' server/api/ | sort` with no per-entry justification, so
 * nothing distinguished "ruled on by the design" from "nobody got to it yet".
 * The check enforces the reason mechanically (see `main`).
 *
 * Regenerate the raw candidate list with:
 *   grep -rl 'getDb(' server/api/ | sort
 *
 * Run: npm run check:handler-rls-context
 */
import { readFileSync, readdirSync } from 'node:fs'
import { resolve, dirname, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const API_DIR = resolve(root, 'server/api')

/**
 * path → why this handler legitimately runs without an RLS lane.
 *
 * Grouped by the reason CLASS, because that is what a reviewer needs to judge:
 * a class with one member is a decision, a class with fifteen is debt.
 */
