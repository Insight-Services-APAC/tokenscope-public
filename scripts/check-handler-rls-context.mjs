/*
 * Detection. `getDb(` alone was too literal: an external review pointed out that
 * `import { getDb as rawDb }` then `rawDb()`, or `getDb?.()`, or `const db = getDb`
 * then `db()`, all reach the platform pool while reading as clean to this check —
 * and the check's own success message claims "every handler carries an RLS lane".
 *
 * So detect the IMPORT as well as the call. A handler cannot reach the pool without
 * naming the module, and the module path is far harder to obfuscate than the call.
 * The import form also catches the aliases by construction: whatever local name the
 * alias binds, the import statement still names `getDb`.
 *
 * This is a drift guard, not a security boundary — someone determined to route around
 * it can, and the review rated it LOW for that reason. The bar it has to clear is
 * "an ordinary handler written next week does not slip through", and a bare
 * `getDb(`-only match did not clear it.
 */
const DIRECT_CALL_RE = /\bgetDb\s*(\?\.)?\s*\(/
const DB_IMPORT_RE = /import\s*(?:type\s*)?\{[^}]*\bgetDb\b[^}]*\}\s*from\s*['"][^'"]*\bdb(?:\/index)?['"]/

/** Recursively list every .ts file under `dir`. Exported for the unit test. */
export function walkTsFiles(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = resolve(dir, entry.name)
    if (entry.isDirectory()) {
      walkTsFiles(full, out)
    } else if (entry.isFile() && entry.name.endsWith('.ts')) {
      out.push(full)
    }
  }
  return out
}

/** True if the handler source reaches the platform pool. Exported for the unit test. */
export function callsGetDbDirectly(source) {
  return DIRECT_CALL_RE.test(source) || DB_IMPORT_RE.test(source)
}

function main() {
  const files = walkTsFiles(API_DIR)
  const seen = new Set()
  let failed = false

  // An entry with no reason is the failure mode this allowlist exists to
  // prevent, so it is a hard error rather than a lint nit.
  for (const [path, reason] of ALLOWLIST) {
    if (typeof reason !== 'string' || reason.trim().length === 0) {
      console.error(`✗ ALLOWLIST entry ${path} has no reason. Every entry must say WHY it has no RLS lane.`)
      failed = true
    }
  }

  for (const file of files) {
    const rel = relative(root, file).split(sep).join('/')
    const body = readFileSync(file, 'utf8')
    if (!callsGetDbDirectly(body)) continue
    seen.add(rel)
    if (!ALLOWLIST.has(rel)) {
      console.error(
        `✗ ${rel}: calls getDb() directly, so its queries carry NO RLS context. Put it on a lane — ` +
          `withRequestRls (server/db/request-rls.ts) for a cookie session, withMachineRls ` +
          `(server/db/machine-rls.ts) for a credential-authenticated device, or withRlsContext ` +
          `(server/db/rls.ts) when you hold an identity directly. If it genuinely has no identity ` +
          `to carry, add it to ALLOWLIST in scripts/check-handler-rls-context.mjs WITH A REASON, ` +
          `and say so in the handler's header too. See docs/design/rls-enforcement.md.`,
      )
      failed = true
    }
  }

  const stale = [...ALLOWLIST.keys()].filter((f) => !seen.has(f))
  if (stale.length > 0) {
    console.log(
      `ℹ ${stale.length} allowlist entr${stale.length === 1 ? 'y' : 'ies'} no longer call(s) getDb() directly — safe to drop (regenerate with: grep -rl 'getDb(' server/api/ | sort):`,
    )
    for (const f of stale) console.log(`  - ${f}`)
  }

  if (failed) {
    process.exit(1)
  }
  console.log(
    `✓ every server/api/** handler carries an RLS lane, except ${ALLOWLIST.size} explicitly-reasoned entries ` +
      `(see ALLOWLIST in this file / docs/design/rls-enforcement.md).`,
  )
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main()
}
